"""Build the self-contained Colab job for the first GR GPU run: tokenise the whole ESCI-US catalogue both ways.

s3-genret is private, so the VM cannot clone it without a credential. Instead this packs `genret/` and
`scripts/tokenize_catalogue.py` from a *committed, clean* tree into one Python file (base64 tarball inside), with the
commit's full SHA recorded. The VM clones s3-search (public) at the referee's pinned full SHA and reads ESCI through
its loader.

    python scripts/build_colab_tokenise_job.py --out results/colab/gr-tokenise-job.py
    python <lab>/.claude/skills/colab-gpu-run/scripts/colab_run.py --session res-grtok1 --gpu L4 \
        --script results/colab/gr-tokenise-job.py --limit 5400 --out-dir results/colab/grtok1 \
        --fetch /content/genret-tok.tar.gz

The job writes /content/genret-tok.tar.gz: for each of GR1 (sentence-t5-base, RQ-VAE 3x256 + 4th code) and GR2
(e5-base-v2, RQ-KMeans 3x8192), and GR1's arm A5 (sentence-t5-base, RQ-KMeans 3x256 + 4th code): sid_map.tsv.gz, tokenise.json and the quantiser's weights. The embeddings stay on the
VM (/content/cache, 3.7 GB each), not in the tarball.
"""
from __future__ import annotations

import argparse
import base64
import io
import subprocess
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
S3_SEARCH_PIN = "767397600d8932511be68c293a7829b021f9b3cb"   # referee/pin.json on steward/referee, 2026-11-13

JOB = r'''#!/usr/bin/env python3
"""GR tokenise job (generated by s3-genret scripts/build_colab_tokenise_job.py at {sha}). Runs detached on the VM."""
import base64, io, json, os, subprocess, sys, tarfile, time
T0 = time.time()
DATASET = sys.argv[1] if len(sys.argv) > 1 else "esci-us"      # esci-sample for the small first check
LABEL = ("development only, never a claim" if DATASET != "esci-us" else
         "GR tokenisation on ESCI-US: the researcher's measurements against GR1-res-5, GR1-res-11 and GR2-res-1; verdicts are the steward's")
def sh(cmd, **kw):
    print("$", " ".join(cmd), flush=True); subprocess.run(cmd, check=True, **kw)
os.chdir("/content")
code = "/content/s3-genret"
os.makedirs(code, exist_ok=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode(PAYLOAD)), mode="r:gz").extractall(code)
if not os.path.exists("/content/s3-search"):
    sh(["git", "clone", "--quiet", "https://github.com/hanialshater/s3-search.git", "/content/s3-search"])
sh(["git", "-C", "/content/s3-search", "checkout", "--quiet", "{pin}"])
if DATASET == "esci-sample":
    sh([sys.executable, "-c", "import sys; sys.path.insert(0, '/content/s3-search'); from referee import loader; loader.fetch('/content/s3-search/data/esci'); print(loader.build_esci_sample('/content/s3-search/data/esci', '/content/s3-search/data/esci-sample')['sha256'])"], cwd="/content/s3-search")
sh([sys.executable, "-m", "pip", "install", "--quiet", "sentence-transformers==3.0.1", "pyarrow", "pandas"])
env = dict(os.environ, S3_SEARCH_ROOT="/content/s3-search", S3_SEARCH_DATA="/content/s3-search/data/esci",
           S3_SEARCH_SAMPLE="/content/s3-search/data/esci-sample", PYTHONPATH=code)
if DATASET == "esci-us":
    sh([sys.executable, "-c", "import sys; sys.path.insert(0, '/content/s3-search'); from referee import loader; loader.fetch('/content/s3-search/data/esci')"], env=env, cwd="/content/s3-search")
sh(["nvidia-smi"])
runs = [
    ("gr1-st5-rqvae-3x256", ["--encoder", "sentence-transformers/sentence-t5-base", "--scheme", "rqvae", "--k", "256",
                             "--steps", "20000", "--batch-size", "512"]),
    ("gr1a5-st5-rqkmeans-3x256", ["--encoder", "sentence-transformers/sentence-t5-base", "--scheme", "rqkmeans",
                                  "--k", "256", "--iters", "20", "--dedup", "--batch-size", "512"]),
    ("gr2-e5-rqkmeans-3x8192", ["--encoder", "intfloat/e5-base-v2", "--scheme", "rqkmeans", "--k", "8192",
                                "--iters", "20", "--batch-size", "512"]),
]
for name, args in runs:
    sh([sys.executable, f"{code}/scripts/tokenize_catalogue.py", "--dataset", DATASET, "--out", f"/content/genret-tok/{name}",
        "--cache", "/content/cache", "--label", LABEL] + args,
       env=env, cwd=code)
json.dump({"code_commit": "{sha}", "dataset": DATASET, "s3_search_pin": "{pin}", "seconds": round(time.time() - T0, 1),
           "utc_end": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}, open("/content/genret-tok/job.json", "w"))
sh(["tar", "czf", "/content/genret-tok.tar.gz", "-C", "/content", "genret-tok"])
print("done", round(time.time() - T0), "s", flush=True)
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--allow-dirty", action="store_true", help="development only")
    a = ap.parse_args()
    sha = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    dirty = subprocess.check_output(["git", "status", "--porcelain", "genret", "scripts"], cwd=ROOT, text=True).strip()
    if dirty and not a.allow_dirty:
        raise SystemExit(f"uncommitted changes under genret/ or scripts/; commit first:\n{dirty}")
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as t:
        for p in sorted((ROOT / "genret").glob("*.py")) + [ROOT / "scripts" / "tokenize_catalogue.py"]:
            t.add(p, arcname=str(p.relative_to(ROOT)))
    payload = base64.b64encode(buf.getvalue()).decode()
    body = JOB.replace("{sha}", sha + ("-dirty" if dirty else "")).replace("{pin}", S3_SEARCH_PIN)
    body = body.replace("os.chdir(\"/content\")", f"PAYLOAD = \"{payload}\"\nos.chdir(\"/content\")", 1)
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(body)
    print(f"wrote {a.out} (code {sha[:12]}{' dirty' if dirty else ''}, payload {len(payload)} bytes)")


if __name__ == "__main__":
    main()
